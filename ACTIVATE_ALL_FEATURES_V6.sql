-- Set status + aktifkan affiliate pembeli + catat komisi inviter ketika pembayaran valid.
create or replace function public.sg_admin_set_status_v6(p_invoice text,p_status text)
returns boolean language plpgsql security definer set search_path=public as $$
declare o public.sg_orders%rowtype; comm bigint:=0; inviter text;
begin
  if not public.sg_is_admin() then raise exception 'Akses admin ditolak'; end if;
  if p_status not in ('Menunggu Pembayaran','Menunggu Verifikasi','Lunas','Dibayar','Diproses','Selesai','Dibatalkan') then
    raise exception 'Status tidak valid';
  end if;
  update public.sg_orders set status=p_status where upper(invoice)=upper(trim(p_invoice)) returning * into o;
  if not found then return false; end if;
  if p_status in ('Lunas','Dibayar','Diproses','Selesai') then
    -- Pembeli otomatis memperoleh affiliate aktif setelah transaksi valid.
    insert into public.sg_affiliates_v6(email,user_id,referral_code,active,updated_at)
    values(lower(o.email),null,'SG'||upper(substr(md5(lower(o.email)),1,8)),true,now())
    on conflict(email) do update set active=true,updated_at=now();

    select r.affiliate_email into inviter from public.sg_referrals_v6 r where r.buyer_email=lower(o.email) limit 1;
    if inviter is not null then
      select coalesce(round(p.commission_amount)::bigint,0) into comm
      from public.sg_catalog_products p where lower(p.name)=lower(o.product_name) order by p.created_at desc limit 1;
      comm:=coalesce(comm,0);
      if comm>0 then
        insert into public.sg_commissions_v6(invoice,affiliate_email,buyer_email,order_amount,commission_amount,status)
        values(o.invoice,inviter,lower(o.email),coalesce(o.price,0),comm,'tersedia')
        on conflict(invoice) do nothing;
      end if;
    end if;
  end if;
  return true;
end $$;

create or replace function public.sg_admin_deliver_access_v6(p_invoice text,p_access_text text,p_access_note text,p_status text)
returns boolean language plpgsql security definer set search_path=public as $$
begin
  if not public.sg_is_admin() then raise exception 'Akses admin ditolak'; end if;
  update public.sg_orders set
    access_text=nullif(trim(p_access_text),''),access_note=nullif(trim(p_access_note),''),
    access_delivered_at=case when nullif(trim(p_access_text),'') is not null then now() else access_delivered_at end,
    status=case when p_status in ('Diproses','Selesai') then p_status else status end
  where upper(invoice)=upper(trim(p_invoice));
  return found;
end $$;

-- Affiliate eligibility + summary.
create or replace function public.sg_affiliate_eligibility_v6()
returns jsonb language plpgsql security definer set search_path=public as $$
declare e text:=lower(coalesce(auth.jwt()->>'email','')); n bigint; c text;
begin
  if e='' then raise exception 'Harus login'; end if;
  select count(*) into n from public.sg_orders where lower(email)=e and status in ('Lunas','Dibayar','Diproses','Selesai');
  if n>0 then perform public.sg_affiliate_sync_self_v6(); end if;
  select referral_code into c from public.sg_affiliates_v6 where email=e limit 1;
  return jsonb_build_object('eligible',n>0,'referral_code',c);
end $$;

create or replace function public.sg_affiliate_me_v6()
returns jsonb language plpgsql security definer set search_path=public as $$
declare e text:=lower(coalesce(auth.jwt()->>'email','')); c text; refs bigint:=0; trx bigint:=0; total bigint:=0; paid bigint:=0; pending bigint:=0; avail bigint:=0;
begin
  if e='' then raise exception 'Harus login'; end if;
  perform public.sg_affiliate_sync_self_v6();
  select referral_code into c from public.sg_affiliates_v6 where email=e;
  select count(*) into refs from public.sg_referrals_v6 where affiliate_email=e;
  select count(*) into trx from public.sg_commissions_v6 where affiliate_email=e;
  select coalesce(sum(commission_amount),0) into total from public.sg_commissions_v6 where affiliate_email=e;
  select coalesce(sum(amount),0) into paid from public.sg_withdrawals_v6 where affiliate_email=e and status='Dibayar';
  select coalesce(sum(amount),0) into pending from public.sg_withdrawals_v6 where affiliate_email=e and status='Diproses';
  avail:=greatest(total-paid-pending,0);
  return jsonb_build_object('referral_code',c,'total_referrals',refs,'total_transactions',trx,
    'total_commission',total,'paid_commission',paid,'pending_withdrawal',pending,'available_balance',avail);
end $$;

