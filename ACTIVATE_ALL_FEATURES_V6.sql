create or replace function public.sg_request_withdraw_v6(p_amount bigint,p_method text,p_account_name text,p_account_number text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare e text:=lower(coalesce(auth.jwt()->>'email','')); total bigint:=0; paid bigint:=0; pending bigint:=0; avail bigint:=0; mn bigint:=10000; new_id bigint;
begin
  if e='' then raise exception 'Harus login'; end if;
  select coalesce(withdraw_minimum,10000) into mn from public.sg_store_settings_ext where id=1;
  select coalesce(sum(commission_amount),0) into total from public.sg_commissions_v6 where affiliate_email=e;
  select coalesce(sum(amount),0) into paid from public.sg_withdrawals_v6 where affiliate_email=e and status='Dibayar';
  select coalesce(sum(amount),0) into pending from public.sg_withdrawals_v6 where affiliate_email=e and status='Diproses';
  avail:=greatest(total-paid-pending,0);
  if coalesce(p_amount,0)<mn then raise exception 'Minimum pencairan Rp %',mn; end if;
  if p_amount>avail then raise exception 'Saldo tersedia tidak cukup'; end if;
  if trim(coalesce(p_account_name,''))='' or trim(coalesce(p_account_number,''))='' then raise exception 'Data rekening wajib lengkap'; end if;
  insert into public.sg_withdrawals_v6(affiliate_email,amount,method,account_name,account_number)
  values(e,p_amount,trim(p_method),trim(p_account_name),trim(p_account_number)) returning id into new_id;
  return jsonb_build_object('ok',true,'id',new_id);
end $$;

