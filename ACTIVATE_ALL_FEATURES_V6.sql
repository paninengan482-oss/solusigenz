-- Sinkronkan akun affiliate. Kode stabil berdasarkan email.
create or replace function public.sg_affiliate_sync_self_v6()
returns jsonb language plpgsql security definer set search_path=public as $$
declare e text:=lower(coalesce(auth.jwt()->>'email','')); u uuid:=auth.uid(); c text; paid_count bigint;
begin
  if e='' then raise exception 'Harus login'; end if;
  c:='SG'||upper(substr(md5(e),1,8));
  select count(*) into paid_count from public.sg_orders o
    where lower(o.email)=e and o.status in ('Lunas','Dibayar','Diproses','Selesai');
  insert into public.sg_affiliates_v6(email,user_id,referral_code,active,updated_at)
  values(e,u,c,paid_count>0,now())
  on conflict(email) do update set user_id=coalesce(excluded.user_id,sg_affiliates_v6.user_id),
    active=(sg_affiliates_v6.active or excluded.active),updated_at=now();
  return jsonb_build_object('email',e,'referral_code',c,'eligible',paid_count>0);
end $$;

create or replace function public.sg_affiliate_attach_referral_v6(p_referral_code text)
returns boolean language plpgsql security definer set search_path=public as $$
declare buyer text:=lower(coalesce(auth.jwt()->>'email','')); uid uuid:=auth.uid(); owner_email text; code text:=upper(trim(coalesce(p_referral_code,'')));
begin
  if buyer='' then raise exception 'Harus login'; end if;
  if code='' then return false; end if;
  select email into owner_email from public.sg_affiliates_v6 where referral_code=code and active=true limit 1;
  if owner_email is null or owner_email=buyer then return false; end if;
  insert into public.sg_referrals_v6(buyer_email,buyer_user_id,affiliate_email,referral_code)
  values(buyer,uid,owner_email,code)
  on conflict(buyer_email) do nothing;
  return true;
end $$;

-- Buat order: email selalu mengikuti akun login, jadi status bisa dibaca kembali dengan aman.
create or replace function public.sg_create_order_v6(
  p_invoice text,p_product_name text,p_price bigint,p_customer_name text,
  p_whatsapp text,p_payment_method text
) returns jsonb language plpgsql security definer set search_path=public as $$
declare e text:=lower(coalesce(auth.jwt()->>'email',''));
begin
  if e='' then raise exception 'Harus login'; end if;
  if trim(coalesce(p_invoice,''))='' then raise exception 'Invoice tidak valid'; end if;
  if trim(coalesce(p_product_name,''))='' then raise exception 'Produk tidak valid'; end if;
  insert into public.sg_orders(invoice,product_name,price,customer_name,email,whatsapp,payment_method,status)
  values(upper(trim(p_invoice)),trim(p_product_name),greatest(0,coalesce(p_price,0)),
         coalesce(nullif(trim(p_customer_name),''),split_part(e,'@',1)),e,trim(coalesce(p_whatsapp,'')),
         coalesce(nullif(trim(p_payment_method),''),'Transfer Bank Mandiri'),'Menunggu Pembayaran');
  return jsonb_build_object('ok',true,'invoice',upper(trim(p_invoice)));
exception when unique_violation then
  raise exception 'Invoice sudah ada, coba lagi';
end $$;

-- Cek order dalam JSON supaya tidak gagal karena perbedaan tipe schema lama.
create or replace function public.sg_check_order_v6(p_invoice text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare e text:=lower(coalesce(auth.jwt()->>'email','')); j jsonb;
begin
  if e='' then raise exception 'Harus login'; end if;
  select jsonb_build_object(
    'invoice',o.invoice,'product_name',o.product_name,'price',o.price,'customer_name',o.customer_name,
    'email',o.email,'whatsapp',o.whatsapp,'payment_method',o.payment_method,'status',o.status,
    'created_at',o.created_at,'payment_proof_data_url',o.payment_proof_data_url,
    'access_text',o.access_text,'access_note',o.access_note,'access_delivered_at',o.access_delivered_at
  ) into j from public.sg_orders o
  where upper(o.invoice)=upper(trim(p_invoice)) and lower(o.email)=e limit 1;
  return j;
end $$;

create or replace function public.sg_submit_payment_v6(p_invoice text,p_proof_data_url text)
returns boolean language plpgsql security definer set search_path=public as $$
declare e text:=lower(coalesce(auth.jwt()->>'email',''));
begin
  if e='' then raise exception 'Harus login'; end if;
  if p_proof_data_url is null or length(p_proof_data_url)<30 then raise exception 'Bukti transfer wajib'; end if;
  update public.sg_orders set payment_proof_data_url=p_proof_data_url,status='Menunggu Verifikasi'
  where upper(invoice)=upper(trim(p_invoice)) and lower(email)=e
    and coalesce(status,'') not in ('Lunas','Dibayar','Diproses','Selesai','Dibatalkan');
  return found;
end $$;

